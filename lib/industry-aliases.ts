// ------------------------------------------------------------------
// 旧業界名 → 現行業界名の対応表。
//
// 【なぜ必要か】
// /industries/[industry] と /lists/[slug] のURLは、スプレッドシートC列の
// 業界名をそのまま使っている。そのため業界名を整理した時点で、
// 旧名のURLが全て404になった。
//
// Search Console（2026-06-19〜09-19）で確認したところ、
// 現行35業界に存在しない旧URLが25本あり、
// それらが17クリック（サイト全体98クリックの17%）を稼いでいた。
// 生きている業界URL33本の12クリックより多い。
//
// 旧名（製薬・証券・半導体）のほうが短く、検索語と一致しやすかったため。
//
// 【この表に載せる基準】
// 統合先が1つに定まるものだけを載せる。
// 「メーカー」「金融」「IT」のように現行の複数業界に分割されたものは
// 載せない。関係の薄いページへ飛ばすとGoogleはソフト404として扱い、
// 素直に404を返すより悪い評価になるため。
//
// 【運用】
// 業界名を変更したら、必ずここに旧名→新名を追加すること。
// 追加を忘れると、その業界のURLは静かに404になる。
// ------------------------------------------------------------------

/**
 * 旧業界名 → 現行業界名。
 * コメントの数値は Search Console 実測（クリック / 表示 / 掲載順位）。
 */
export const INDUSTRY_ALIASES: Record<string, string> = {
  製薬: "製薬・バイオ", //        6clk /  17imp /  6.0位  ← サイト第2のクリック源だった
  バイオ: "製薬・バイオ", //      0clk /   4imp / 28.5位
  証券: "証券・投資銀行", //      2clk /  32imp / 13.8位
  出版: "出版・メディア", //      1clk /  19imp / 12.9位
  メディア: "出版・メディア", //  0clk /   5imp / 14.4位
  エンタメ: "エンタメ・IP", //    1clk /  11imp / 28.6位
  IP: "エンタメ・IP", //          0clk /   1imp /  9.0位
  広告代理店: "広告・PR", //      1clk /  10imp /  5.2位
  半導体: "半導体・電子部品", //  0clk /  21imp /  8.6位
  自動車: "自動車・産業機械", //  0clk /   7imp /  3.7位
  SaaS: "SaaS・クラウド", //      0clk /   7imp / 14.7位
  ITコンサル: "IT・DXコンサル", // 0clk /  5imp / 23.6位
  Sler: "SIer・IT開発", //        0clk /   3imp /  7.7位  ← SIerの綴り誤りが流入していた
  税理士法人: "監査・士業", //    0clk /   3imp /  8.3位
  "M&A仲介": "M&A・事業再生", //  0clk /   2imp /  4.5位
  事業再生: "M&A・事業再生", //   0clk /   1imp / 10.0位
  医療: "医療・ヘルスケア", //    /lists/医療--over-35man が 1clk / 3.6位
}

/**
 * 旧名なら現行名を返す。旧名でなければ null。
 *
 * 現行の業界一覧を渡して、行き先が実在することを確認する。
 * スプシ側でさらに名前が変わっていた場合に、
 * 存在しない業界へリダイレクトしてリダイレクトループや
 * 404の連鎖を起こさないため。
 */
export function resolveIndustryAlias(
  name: string,
  currentIndustries: readonly string[],
): string | null {
  const target = INDUSTRY_ALIASES[name.trim()]
  if (!target) return null
  if (!currentIndustries.includes(target)) return null
  // 念のため: 自分自身への転送は無意味なので弾く
  if (target === name.trim()) return null
  return target
}
