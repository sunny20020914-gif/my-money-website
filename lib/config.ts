// サイト全体で共有する定数。
// ドメイン変更や年度更新はこのファイルだけを修正すれば済むようにする。

export const SITE_URL = "https://www.mymoneyweb.com"
export const SITE_NAME = "My Money Web"
/**
 * データの対象年度（西暦）。
 *
 * 【重要】これは「卒業年度」ではなく「掲載している初任給データが何年度のものか」を表す。
 * 表記する際は「2026年度の初任給データ」「2026年最新」のように使い、
 * 「2026年新卒」とは書かないこと。読者に26卒向けサイトだと誤解される。
 *
 * 年度を更新するときは、この1行だけを変更すれば
 * タイトル・見出し・卒業年度の表記まで全て追従する。
 */
export const FISCAL_YEAR = 2026

/**
 * 主な想定読者の卒業年度（西暦下2桁の数値）。例: [27, 28]
 *
 * FISCAL_YEAR年度に就職活動をしているのは、その翌年・翌々年に卒業する学生。
 * FISCAL_YEAR を変えるだけで自動的に繰り上がる。
 *
 * /grad/[grad] ページの generateStaticParams はこの配列を元に生成される。
 * 対象学年を増やしたい場合は offsets に 3 を足すだけでページが増える。
 */
const GRAD_OFFSETS = [1, 2] as const
export const TARGET_GRADS: readonly number[] = GRAD_OFFSETS.map(
  (offset) => (FISCAL_YEAR + offset) % 100,
)

/**
 * 卒業年度の西暦フル表記（例: [2027, 2028]）。
 *
 * 【なぜ必要か】Search Consoleの実測で、
 *   「初任給ランキング 2026」  9.7位
 *   「初任給ランキング 2027」 11.1位
 *   「初任給 ランキング」（年号なし） 45.0位
 * と、年号を付けたクエリだけ大きく順位が良い。
 * 年号なしの「初任給ランキング」は大手メディアの領域で勝ち目が薄く、
 * 年号付きは競合が薄いため、そちらを明示的に狙う。
 *
 * 【表記の注意】FISCAL_YEAR（データの年度）とは別物。
 * 「2026年新卒」と書くと26卒向けサイトだと誤読されるため、
 * 卒業年度を指すときは必ずこちらを使うこと。
 */
export const TARGET_GRAD_YEARS: readonly number[] = TARGET_GRADS.map((g) => 2000 + g)

/** 卒業年度の表示用ラベル（例: "27卒・28卒"）。TARGET_GRADS と必ず一致する */
export const TARGET_GRAD_LABEL = TARGET_GRADS.map(
  (g) => `${String(g).padStart(2, "0")}卒`,
).join("・")

// ------------------------------------------------------------------
// 【卒業年度の西暦表記】
//
// Search Consoleの実測で、年号の有無が順位を大きく分けることが分かった。
//   初任給ランキング 2026 …  9.7位
//   初任給ランキング 2027 … 11.1位
//   初任給 ランキング（年号なし） … 45.0位
//
// 「初任給ランキング」単体は東洋経済・日経・大手就活サイトの領域で、
// 新規ドメインが正面から勝てる相手ではない。一方、年号を付けたクエリは
// 競合が薄く既に10位前後を取れている。
//
// 就活生は自分の卒業年度で検索するため、データの年度（FISCAL_YEAR）
// だけでなく卒業年度の西暦もページに載せる必要がある。
//
// 【重要】FISCAL_YEAR は「データが何年度のものか」であり卒業年度ではない。
// 混同すると「2026年新卒向けサイト」と誤読されるので、
// 用途に応じて必ず使い分けること。
// ------------------------------------------------------------------

/** 西暦での表示用ラベル（例: "2027年卒・2028年卒"） */
export const TARGET_GRAD_YEAR_LABEL = TARGET_GRAD_YEARS.map((y) => `${y}年卒`).join("・")

/** タイトル用の短い表記（例: "2027・2028年卒"） */
export const TARGET_GRAD_YEAR_SHORT =
  TARGET_GRAD_YEARS.length > 1
    ? `${TARGET_GRAD_YEARS.slice(0, -1).join("・")}・${TARGET_GRAD_YEARS.at(-1)}年卒`
    : `${TARGET_GRAD_YEARS[0]}年卒`

// ------------------------------------------------------------------
// 【ISR（再生成）の間隔】
//
// Vercelは再生成したページをキャッシュに書き込むたびに「ISR Writes」を
// 消費する。ただし再生成しても出力が前回と1バイトも変わらなければ
// 書き込みは発生しない。つまり課金を決めるのは
//   ①どれくらいの頻度で再生成するか
//   ②再生成のたびに出力が変わるか
// の2つ。
//
// 以前は全ページが revalidate = 3600（1時間）で、さらに最終更新日に
// ミリ秒まで含む new Date().toISOString() を出力していたため、
// 1時間ごとに全ページのHTMLが別物になり、毎回書き込みが発生していた。
//   企業180 + 条件40 + 卒年2 ≒ 222ページ × 24回/日 × 30日 ≒ 16万回/月
// これが無料枠20万回の75%に達した原因。
//
// 対策は2つ。日付を日単位に固定して出力を安定させること（lib/updated-at.ts）と、
// 更新頻度に見合った間隔をここで一元管理すること。
//
// 【間隔の決め方】データ源はGoogleスプレッドシートで、更新は多くても
// 週に数回。1時間ごとに取りに行く必要はまったくない。
// すぐ反映したいときは /api/revalidate を叩けばよい。
// ------------------------------------------------------------------

/**
 * ランキングなど、データ更新をなるべく早く反映したいページ（6時間）。
 * ページ数が少ないため短くしても書き込み量は問題にならない。
 */
export const REVALIDATE_FRESH = 60 * 60 * 6

/**
 * 企業詳細・業界・条件一覧・記事など、数が多く内容もほとんど変わらないページ（24時間）。
 * ここを1時間から24時間にすることで書き込みが1/24になる。
 */
export const REVALIDATE_STABLE = 60 * 60 * 24

/** sitemapやllms.txtなど、機械向けで頻繁な更新が不要なもの（24時間） */
export const REVALIDATE_MACHINE = 60 * 60 * 24
